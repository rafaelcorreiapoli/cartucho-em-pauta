    Reflect.set(caioAgenda,'missions',[]);
    match.refreshAgendaEligibility();
    await wait(()=>views.get(caio.sessionId)?.politics?.missions.active.find(mission=>mission.kind==='publicouSelfie'));
    Reflect.get(Reflect.get(room,'internalMail'),'cooldowns').delete(caio.sessionId);
    caio.send('mail-publish',{token:1590,subject:'Mesma foto',body:'Publicada novamente',attachment:{kind:'photo',id:photo.id}});
    await wait(()=>inboxes.get(alice.sessionId)?.find(entry=>entry.subject==='Mesma foto'));
    move(caio,stations.press);
    feedback.delete(caio.sessionId);
    caio.send('gameplay',{action:{kind:'photo-publish',item:photo.id},token:1600});
    await wait(()=>feedback.get(caio.sessionId)==='Fotografia publicada no álbum público.');

    Reflect.get(Reflect.get(room,'internalMail'),'cooldowns').delete(caio.sessionId);
    caio.send('mail-publish',{token:2,subject:'Reenvio',body:'Não deve publicar'});
    caio.send('mail-publish',{token:1630,subject:'Enc: Proposta assinada',body:'Revisem a proposta',forwardedFrom:publication.id});
    const forwarded = await wait(()=>inboxes.get(alice.sessionId)?.find(entry=>entry.forwardedFrom===publication.id));
    expect(forwarded.attachment).toEqual(publication.attachment);
    expect(forwarded.author).toBe('Caio');
    expect(views.get(caio.sessionId)?.politics?.missions.completed.filter(mission=>mission.kind==='publicouSelfie')).toEqual([completedSelfie]);
    expect(inboxes.get(alice.sessionId)?.some(entry=>entry.subject==='Reenvio')).toBe(false);
    expect(JSON.stringify(forwarded)).not.toContain('authentic');
    feedback.delete(alice.sessionId);
    await submitAtProtocol(original.id,1710);
    await wait(()=>feedback.get(alice.sessionId)==='O documento não atende aos requisitos formais.');
    expect(views.get(alice.sessionId)?.project).toBeUndefined();
    economy.changePopularity(alice.sessionId,40);
    move(alice,stations.panel);
    alice.send('politics',{kind:'hearing',target:bia.sessionId,token:1780});
    await Bun.sleep(250);
    expect(views.get(bia.sessionId)?.phase).toBe('negotiation');
    expect(controls.get(bia.sessionId)?.isolated).toBeFalsy();

    // File a second, authentic document through the public gameplay messages.
    move(alice,stations.secretary);
    alice.send('gameplay',{action:{kind:'supply',place:'secretary',target:'project-1'},token:1980});
    const fresh = await wait(()=>state(alice)?.inventory.find(item=>item.document?.project===1));
    expect(fresh.document).toMatchObject({requiredSignatures:2,requiredStamps:[]});
    move(caio,{x:stations.secretary.x+8,y:stations.secretary.y});
    alice.send('gameplay',{action:{kind:'sign-request',item:fresh.id,target:caio.sessionId},token:2030});
    const freshRequest = await wait(()=>state(caio)?.requests.find(entry=>entry.item.id===fresh.id));
    caio.send('gameplay',{action:{kind:'accept',item:freshRequest.id},token:2050});
    await wait(()=>state(alice)?.inventory.find(item=>item.id===fresh.id && item.document?.signatures.length));
    move(bia,{x:stations.secretary.x-8,y:stations.secretary.y});
    alice.send('gameplay',{action:{kind:'sign-request',item:fresh.id,target:bia.sessionId},token:2080});
    const secondSignature = await wait(()=>state(bia)?.requests.find(entry=>entry.item.id===fresh.id));
    bia.send('gameplay',{action:{kind:'accept',item:secondSignature.id},token:2090});
    await wait(()=>state(alice)?.inventory.find(item=>item.id===fresh.id && item.document?.signatures.length===2));
    await submitAtProtocol(fresh.id,2110);
    await wait(()=>views.get(alice.sessionId)?.project===1);
    expect(views.get(bia.sessionId)?.proposer).toBe('Alice');
    expect(views.get(caio.sessionId)?.proposer).toBe('Alice');
    Reflect.get(match,'proposal').voteAt = room.clock.currentTime;
    await wait(()=>views.get(bia.sessionId)?.phase==='ballot');
    expect(views.get(bia.sessionId)).toMatchObject({project:1,proposer:'Alice'});

    Reflect.set(match,'ends',room.clock.currentTime);
    await wait(()=>views.get(bia.sessionId)?.phase==='negotiation');
    // A new command token does not make an already filed item available again.
    const replay = await submitAtProtocol(fresh.id,2120);
    await wait(()=>feedback.get(alice.sessionId)==='Opção indisponível.');
    expect(replay.options.some(option=>option.id===`file-${fresh.id}`)).toBe(false);
    expect(views.get(alice.sessionId)?.project).toBeUndefined();
    const fire = Reflect.get(match,'fire');
    const infiltrator = rooms.find(peer=>views.get(peer.sessionId)?.role==='Infiltrado')!;
    const firefighter = rooms.find(peer=>peer!==infiltrator)!;
    const remote = rooms.find(peer=>peer!==infiltrator && peer!==firefighter)!;
    const site = fireSites[0];
    move(remote,stations.secretary);
    // Earlier mail fees and transfers can leave a different wallet based on the role draw.
    const purchaseShortfall = Math.round((incendiary.price-economy.wallet(firefighter.sessionId))*10)/10;
    if (purchaseShortfall>0) economy.rewardFromReserve(firefighter.sessionId,purchaseShortfall);
    move(firefighter,{x:npcs.vendor.x,y:npcs.vendor.y+11});
    const previousShopToken = state(firefighter)?.dialogue?.token;
    firefighter.send('gameplay',{action:{kind:'open-shop',target:'vendor'},token:2230});
    const technical = await wait(()=>{
      const current = state(firefighter)?.dialogue;
      return current?.npc==='vendor' && current.shop && current.token!==previousShopToken ? current : undefined;
    });
    feedback.delete(firefighter.sessionId);
    firefighter.send('gameplay',{action:{kind:'shop-buy',target:'incendiary',token:technical.token},token:2240});
    expect(await wait(()=>feedback.get(firefighter.sessionId))).toBe('Compra guardada no inventário.');
    await wait(()=>state(firefighter)?.inventory.some(item=>item.kind==='incendiary'));
    const nearbyTarget = {x:site.x,y:site.y+10};
    move(firefighter,nearbyTarget);
    move(infiltrator,nearbyTarget);
    await wait(()=>views.get(firefighter.sessionId)?.fireInteraction?.option?.kind==='plant');
    firefighter.send('fire-action',{kind:'plant',site:0,token:2260});
