import {fireRules,fireSites} from '../src/fire';
import {expect,test} from 'bun:test';
import {Client,type Room} from '@colyseus/sdk';
import {defineRoom,defineServer,matchMaker} from 'colyseus';
import {BunWebSockets} from '@colyseus/bun-websockets';
import {SessionRoom} from './SessionRoom';
import {PlenaryMatch} from './PlenaryMatch';
import type {ControlState} from '../src/movement';
import {SUSPENSION_MS} from '../src/politics';
import {inPlenary,isolationRoom,type Player} from '../src/map';
import {stations,type PlenaryView} from '../src/plenary';
import {reprography} from '../src/room-activities';
import {npcs} from '../src/npcs';
import type {PhotoAccessView} from '../src/photography';
import type {ForensicReport,InternalNotice} from '../src/internal-mail';

test('players sign, publish, alter, examine and counterpublish snapshots over the room socket',async()=>{
  const reservation = Bun.serve({hostname:'127.0.0.1',port:0,fetch:()=>new Response()});
  const port = reservation.port!;
  await reservation.stop();
  const server = defineServer({gracefullyShutdown:false,transport:new BunWebSockets(),rooms:{plenary:defineRoom(SessionRoom)}});
  const rooms:Room[] = [];
  async function wait<T>(read:()=>T|undefined):Promise<T> {
    for (let attempt=0;attempt<160;attempt++) {
      const result = read();
      if (result) return result;
      await Bun.sleep(25);
    }
    throw new Error('Expected room state did not arrive');
  }
  try {
    await server.listen(port,'127.0.0.1');
    const client = new Client('http://127.0.0.1:'+port);
    const alice = await client.create('plenary',{nick:'Alice'});
    rooms.push(alice);
    const bia = await client.joinById(alice.roomId,{nick:'Bia'});
    rooms.push(bia);
    const caio = await client.joinById(alice.roomId,{nick:'Caio'});
    rooms.push(caio);
    const views = new Map<string,PlenaryView>();
    const inboxes = new Map<string,InternalNotice[]>();
    const photos = new Map<string,PhotoAccessView>();
    const mailErrors = new Map<string,string|null>();
    const feedback = new Map<string,string>();
    const controls = new Map<string,ControlState>();
    const reports = new Map<string,ForensicReport[]>();
    const pixNotices = new Map<string,{from:string;amount:number}>();
    for (const peer of rooms) {
      peer.onMessage('pix-received',(notice:{from:string;amount:number})=>pixNotices.set(peer.sessionId,notice));
      peer.onMessage('audit-result',()=>{});
      peer.onMessage('plenary',(view:PlenaryView)=>views.set(peer.sessionId,view));
      peer.onMessage('mail-state',(mail:InternalNotice[])=>inboxes.set(peer.sessionId,mail));
      peer.onMessage('mail-reports',(mail:ForensicReport[])=>reports.set(peer.sessionId,mail));
      peer.onMessage('photo-state',(view:PhotoAccessView)=>photos.set(peer.sessionId,view));
      peer.onMessage('mail-result',(error:string|null)=>mailErrors.set(peer.sessionId,error));
      peer.onMessage('control',(state:ControlState)=>controls.set(peer.sessionId,state));
      peer.onMessage('gameplay-feedback',(message:string)=>feedback.set(peer.sessionId,message));
      for (const name of ['players','item-obtained']) peer.onMessage(name,()=>{});
    }
    const room = matchMaker.getLocalRoomById(alice.roomId) as SessionRoom;
    const match = new PlenaryMatch(1);
    Reflect.set(room,'match',match);
    const players = Reflect.get(room,'players') as Map<string,{player:Player}>;
    const move = (peer:Room,point:{x:number;y:number})=>Object.assign(players.get(peer.sessionId)!.player,point);
    const state = (peer:Room)=>views.get(peer.sessionId)?.gameplay;
    alice.send('start-match',{npcs:0,token:1});
    await wait(()=>state(alice));
    const economy = Reflect.get(match,'economy');
    const account = Reflect.get(economy,'accounts').get(alice.sessionId);
    // Choose a deterministic agenda draw; the match still assigns the target and validates the signature.
    Reflect.set(account.agenda,'missions',[]);
    Reflect.set(account.agenda,'missionDeck',['assinaturaAlvo','cafe','passeio']);
    match.refreshAgendaEligibility();
    await wait(()=>views.get(alice.sessionId)?.politics?.missions.active.find(mission=>mission.kind==='assinaturaAlvo'));
    expect(views.get(alice.sessionId)?.politics?.missions.active.find(mission=>mission.kind==='assinaturaAlvo')?.person?.id).toBe(bia.sessionId);
    expect(views.get(bia.sessionId)?.politics?.missions.active.some(mission=>mission.person?.id===bia.sessionId)).toBe(false);
    move(alice,stations.secretary);
    move(bia,{x:stations.secretary.x+8,y:stations.secretary.y});
    alice.send('gameplay',{action:{kind:'supply',place:'secretary',target:'project-0'},token:760});
    const original = await wait(()=>state(alice)?.inventory.find(item=>item.document?.project===0));
    alice.send('gameplay',{action:{kind:'verify-document',item:original.id,place:'secretary'},token:780});
    await wait(()=>feedback.get(alice.sessionId)?.startsWith('Falta:'));
    expect(feedback.get(alice.sessionId)).toContain('assinatura');
    move(caio,{x:stations.secretary.x-8,y:stations.secretary.y});
    alice.send('gameplay',{action:{kind:'sign-request',item:original.id,target:caio.sessionId},token:820});
    const wrongSigner = await wait(()=>state(caio)?.requests.find(item=>item.kind==='signature'));
    caio.send('gameplay',{action:{kind:'accept',item:wrongSigner.id},token:840});
    await wait(()=>state(alice)?.inventory.find(item=>item.document?.signatures.some(signer=>signer.id===caio.sessionId)));
    expect(views.get(alice.sessionId)?.politics?.missions.completed.some(mission=>mission.kind==='assinaturaAlvo')).toBe(false);
    alice.send('gameplay',{action:{kind:'sign-request',item:original.id,target:bia.sessionId},token:870});
    const request = await wait(()=>state(bia)?.requests.find(item=>item.kind==='signature'));
    bia.send('gameplay',{action:{kind:'accept',item:request.id},token:890});
    await wait(()=>state(alice)?.inventory.find(item=>item.document?.signatures.some(signer=>signer.id===bia.sessionId)));
    await wait(()=>views.get(alice.sessionId)?.politics?.missions.completed.find(mission=>mission.kind==='assinaturaAlvo'));
    alice.send('mail-publish',{token:930,subject:'Original assinado',body:'Segue o original',attachment:{kind:'document',id:original.id}});
    const authenticPublication = await wait(()=>inboxes.get(bia.sessionId)?.find(entry=>entry.subject==='Original assinado'));
    move(alice,reprography);
    alice.send('gameplay',{action:{kind:'edit',item:original.id,target:'1'},token:960});
    await wait(()=>state(alice)?.forgeryRemaining);
    expect(state(alice)?.inventory.find(item=>item.id===original.id)?.document?.project).toBe(0);
    await Bun.sleep(4900);
    await wait(()=>state(alice)?.inventory.find(item=>item.document?.project===1));
    move(alice,stations.secretary);
    alice.send('gameplay',{action:{kind:'verify-document',item:original.id,place:'secretary'},token:1020});
    await wait(()=>feedback.get(alice.sessionId)==='O documento não atende aos requisitos formais.');
    // Advance the rate-limit boundary without waiting through a full game phase.
    Reflect.get(Reflect.get(room,'internalMail'),'cooldowns').delete(alice.sessionId);
    alice.send('mail-publish',{token:1070,subject:'Proposta assinada',body:'Segue documento',attachment:{kind:'document',id:original.id}});
    const publication = await wait(()=>inboxes.get(bia.sessionId)?.find(entry=>entry.subject==='Proposta assinada'));
    expect(publication.attachment).toMatchObject({kind:'document',document:{id:original.id,signatures:['Caio','Bia']}});
    expect(JSON.stringify(publication)).not.toContain('authentic');
    move(alice,reprography);
    alice.send('gameplay',{action:{kind:'edit',item:original.id,target:'2'},token:1120});
    await wait(()=>state(alice)?.forgeryRemaining);
    await Bun.sleep(4900);
    await wait(()=>state(alice)?.inventory.find(item=>item.document?.project===2));
    bia.send('mail-read');
    await Bun.sleep(100);
    expect(inboxes.get(bia.sessionId)?.find(entry=>entry.subject==='Proposta assinada')).toEqual(publication);
    move(bia,{x:npcs.vendor.x,y:npcs.vendor.y+11});
    bia.send('gameplay',{action:{kind:'talk',target:'vendor'},token:1200});
    const dialogue = await wait(()=>state(bia)?.dialogue);
    bia.send('gameplay',{action:{kind:'dialogue-choice',target:'products',token:dialogue.token},token:1220});
    const shop = await wait(()=>state(bia)?.dialogue?.shop ? state(bia)?.dialogue : undefined);
    bia.send('gameplay',{action:{kind:'shop-buy',target:'forensicKit',token:shop.token},token:1240});
    await wait(()=>state(bia)?.inventory.find(item=>item.kind==='forensicKit'));
    bia.send('mail-examine',{notice:publication.id,token:1260});
    const report = await wait(()=>reports.get(bia.sessionId)?.[0]);
    expect(report.authentic).toBe(false);
    expect(reports.get(alice.sessionId)).toEqual([]);
    await wait(()=>state(bia)?.inventory.some(item=>item.kind==='forensicKit')===false);
    move(caio,stations.secretary);
    caio.send('politics',{kind:'transfer',to:bia.sessionId,amount:4,clandestine:false,token:1320});
    const pix = await wait(()=>views.get(bia.sessionId)?.politics?.evidence.find(entry=>
      entry.kind==='clandestine-transfer' && entry.from===caio.sessionId && entry.to===bia.sessionId && entry.amount===4));
    expect([...pixNotices]).toEqual([[bia.sessionId,{from:'Caio',amount:4}]]);
    const alicePolitics = () => views.get(alice.sessionId)?.politics;
    expect(alicePolitics()?.evidence.some(entry=>entry.id===pix.id)).toBe(false);
    expect(alicePolitics()?.ledger.some(entry=>entry.id===pix.id)).toBe(false);
    move(alice,stations.audit);
    alice.send('plenary-action',{action:'audit',token:1330});
    await wait(()=>alicePolitics()?.evidence.find(entry=>entry.id===pix.id));
    expect(alicePolitics()?.ledger.some(entry=>entry.id===pix.id)).toBe(false);
    const nextShop = await wait(()=>{
      const current = state(bia)?.dialogue;
      return current?.shop && current.token!==shop.token ? current : undefined;
    });
    bia.send('gameplay',{action:{kind:'shop-buy',target:'forensicKit',token:nextShop.token},token:1390});
    await wait(()=>state(bia)?.inventory.find(item=>item.kind==='forensicKit'));
    bia.send('mail-examine',{notice:authenticPublication.id,token:1});
    bia.send('mail-examine',{notice:authenticPublication.id,token:1420});
    const originalReport = await wait(()=>reports.get(bia.sessionId)?.find(entry=>entry.notice===authenticPublication.id));
    expect(originalReport.authentic).toBe(true);
    expect(reports.get(alice.sessionId)).toEqual([]);
    bia.send('mail-publish',{token:1470,subject:'Contraexposição',body:'Laudo anexo',attachment:{kind:'report',id:report.notice}});
    const rebuttal = await wait(()=>inboxes.get(alice.sessionId)?.find(entry=>entry.subject==='Contraexposição'));
    expect(rebuttal.attachment).toEqual({kind:'report',report});

    const caioAgenda = Reflect.get(economy,'accounts').get(caio.sessionId).agenda;
    Reflect.set(caioAgenda,'missions',[]);
    Reflect.set(caioAgenda,'missionDeck',['publicouSelfie','cafe','passeio']);
    match.refreshAgendaEligibility();
    await wait(()=>views.get(caio.sessionId)?.politics?.missions.active.find(mission=>mission.kind==='publicouSelfie'));
    move(caio,stations.audit);
    move(alice,stations.audit);
    move(bia,stations.audit);
    caio.send('gameplay',{action:{kind:'selfie'},token:1520});
    const photo = await wait(()=>photos.get(caio.sessionId)?.album[0]?.photo);
    Reflect.get(Reflect.get(room,'internalMail'),'cooldowns').delete(bia.sessionId);
    bia.send('mail-publish',{token:1550,subject:'Foto alheia',body:'Tentativa',attachment:{kind:'photo',id:photo.id}});
    await wait(()=>mailErrors.get(bia.sessionId)==='Anexo indisponível.');
    caio.send('mail-publish',{token:1570,subject:'Selfie na Corregedoria',body:'Segue a foto',attachment:{kind:'photo',id:photo.id}});
    const photoNotice = await wait(()=>inboxes.get(alice.sessionId)?.find(entry=>entry.subject==='Selfie na Corregedoria'));
    expect(photoNotice.attachment).toEqual({kind:'photo',photo});
    const completedSelfie = await wait(()=>views.get(caio.sessionId)?.politics?.missions.completed.find(mission=>mission.kind==='publicouSelfie'));
    Reflect.set(caioAgenda,'missionDeck',['publicouSelfie','cafe','passeio','selfieSolo']);
    Reflect.set(caioAgenda,'missions',[]);
    match.refreshAgendaEligibility();
    await wait(()=>views.get(caio.sessionId)?.politics?.missions.active.find(mission=>mission.kind==='publicouSelfie'));
    Reflect.get(Reflect.get(room,'internalMail'),'cooldowns').delete(caio.sessionId);
    caio.send('mail-publish',{token:1590,subject:'Mesma foto',body:'Publicada novamente',attachment:{kind:'photo',id:photo.id}});
    await wait(()=>inboxes.get(alice.sessionId)?.find(entry=>entry.subject==='Mesma foto'));

    Reflect.get(Reflect.get(room,'internalMail'),'cooldowns').delete(caio.sessionId);
    caio.send('mail-publish',{token:2,subject:'Reenvio',body:'Não deve publicar'});
    caio.send('mail-publish',{token:1630,subject:'Enc: Proposta assinada',body:'Revisem a proposta',forwardedFrom:publication.id});
    const forwarded = await wait(()=>inboxes.get(alice.sessionId)?.find(entry=>entry.forwardedFrom===publication.id));
    expect(forwarded.attachment).toEqual(publication.attachment);
    expect(forwarded.author).toBe('Caio');
    expect(views.get(caio.sessionId)?.politics?.missions.completed.filter(mission=>mission.kind==='publicouSelfie')).toEqual([completedSelfie]);
    expect(inboxes.get(alice.sessionId)?.some(entry=>entry.subject==='Reenvio')).toBe(false);
    expect(JSON.stringify(forwarded)).not.toContain('authentic');
    move(alice,stations.amendment);
    feedback.delete(alice.sessionId);
    alice.send('gameplay',{action:{kind:'file',item:original.id,place:'protocol'},token:1710});
    await wait(()=>feedback.get(alice.sessionId)==='O documento não atende aos requisitos formais.');
    expect(views.get(alice.sessionId)?.queuedProjects).toEqual([]);
    economy.changePopularity(alice.sessionId,40);
    move(alice,stations.panel);
    const prematureVote = {vote:'no',token:1760};
    alice.send('bill-vote',prematureVote);
    alice.send('politics',{kind:'hearing',target:bia.sessionId,token:1780});
    await wait(()=>views.get(bia.sessionId)?.phase==='hearing' && controls.get(bia.sessionId)?.plenary);
    expect(inPlenary(controls.get(bia.sessionId)!.player)).toBe(true);
    alice.send('bill-vote',{vote:'yes',token:1810});
    alice.send('bill-vote',prematureVote);
    caio.send('bill-vote',{vote:'yes',token:1830});
    await wait(()=>views.get(alice.sessionId)?.hearing?.voted===2);
    expect(views.get(alice.sessionId)?.hearing?.vote).toBe('yes');
    Reflect.set(match,'ends',room.clock.currentTime);
    await wait(()=>controls.get(bia.sessionId)?.isolated);
    expect(controls.get(bia.sessionId)?.player).toMatchObject(isolationRoom.spawn);
    expect(views.get(bia.sessionId)?.isolationSeconds).toBe(60);
    expect(state(bia)).toBeUndefined();
    const accountBia = Reflect.get(economy,'accounts').get(bia.sessionId);
    accountBia.suspendedUntil -= SUSPENSION_MS;
    await wait(()=>controls.get(bia.sessionId)?.isolated===false);
    expect(controls.get(bia.sessionId)?.player).toMatchObject(isolationRoom.exit);

    // File a second, authentic document through the public gameplay messages.
    move(alice,stations.secretary);
    alice.send('gameplay',{action:{kind:'supply',place:'secretary',target:'project-1'},token:1980});
    const fresh = await wait(()=>state(alice)?.inventory.find(item=>item.document?.project===1));
    alice.send('gameplay',{action:{kind:'stamp',place:'secretary',item:fresh.id},token:2000});
    await wait(()=>state(alice)?.inventory.find(item=>item.id===fresh.id && item.document?.stamps.includes('Secretaria')));
    move(caio,{x:stations.secretary.x+8,y:stations.secretary.y});
    alice.send('gameplay',{action:{kind:'sign-request',item:fresh.id,target:caio.sessionId},token:2030});
    const freshRequest = await wait(()=>state(caio)?.requests.find(entry=>entry.item.id===fresh.id));
    caio.send('gameplay',{action:{kind:'accept',item:freshRequest.id},token:2050});
    await wait(()=>state(alice)?.inventory.find(item=>item.id===fresh.id && item.document?.signatures.length));
    move(alice,stations.cabinet);
    alice.send('gameplay',{action:{kind:'stamp',place:'cabinet',item:fresh.id},token:2080});
    await wait(()=>state(alice)?.inventory.find(item=>item.id===fresh.id && item.document?.stamps.includes('Gabinete')));
    move(alice,stations.amendment);
    alice.send('gameplay',{action:{kind:'file',place:'protocol',item:fresh.id},token:2110});
    await wait(()=>views.get(alice.sessionId)?.queuedProjects?.includes(1));
    Reflect.set(match,'ends',room.clock.currentTime);
    await wait(()=>views.get(bia.sessionId)?.phase==='ballot');
    expect(views.get(bia.sessionId)?.project).toBe(1);

    Reflect.set(match,'ends',room.clock.currentTime);
    await wait(()=>views.get(bia.sessionId)?.phase==='negotiation');
    const fire = Reflect.get(match,'fire');
    Reflect.set(fire,'clock',fireRules.firstAfter/2);
    const infiltrator = rooms.find(peer=>views.get(peer.sessionId)?.role==='Infiltrado')!;
    const firefighter = rooms.find(peer=>peer!==infiltrator)!;
    await wait(()=>views.get(infiltrator.sessionId)?.sabotageFireSite===0);
    expect(views.get(firefighter.sessionId)?.sabotageFireSite).toBeUndefined();
    move(infiltrator,fireSites[0]);
    infiltrator.send('fire-action',{kind:'ignite',site:0,token:2260});
    await wait(()=>views.get(firefighter.sessionId)?.fire?.site===0);
    move(firefighter,fireSites[0].extinguisher);
    firefighter.send('fire-action',{kind:'extinguish',site:0,token:2290});
    await wait(()=>feedback.get(firefighter.sessionId)==='Incêndio apagado.');
    await wait(()=>views.get(infiltrator.sessionId)?.fire===undefined);
  } finally {
    await Promise.allSettled(rooms.map(room=>room.leave()));
    await server.gracefullyShutdown(false);
  }
},20_000);
